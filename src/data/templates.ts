/**
 * A two-part card. Its sentence runs THROUGH the deco rows -
 * "you are .. the CALM in my CHAOS" - so the deco is not ornament here, it is
 * grammar. That is why every card names its own connecting words instead of
 * sharing one row: with someone else's words in the middle it reads as
 * gibberish.
 *
 * The middle row is deliberately lighter than the one on the pair that came
 * before: with two lines at size 44 the tags alone cost 126 bytes, which left
 * the longer sayings over the 255-byte ceiling.
 */
const two = (l: string, lead: string, art: string, loud1: string, mid: string, loud2: string): TplItem =>
  it(l, loud1, art, loud2, { ...LOOK_B, deco: deco(`▶ .. ${lead} .. ◀`, `° ✦ ${mid} ✦ °`, '↖(✿ ∩◡∩)↗') });

