/**
 * Puts a card onto a gift. A card may override its category's look; each field
 * it names replaces the category's outright (it is not merged key by key),
 * which is how Cute Notes runs two designs in one category.
 *
 * One function so the gift a click builds and the gift the tests measure are
 * the same gift.
 */
export function composeTemplate(s: GiftState, cat: TplCategory, item: TplItem): GiftState {
  const th = { ...cat.theme, ...item.theme };
  const text = { ...s.text, mainText: item.main, topText: item.top, bottomText: item.bottom };
  if (th.deco.dekoTop != null) text.dekoTop = th.deco.dekoTop;
  if (th.deco.dekoBottom != null) text.dekoBottom = th.deco.dekoBottom;
  if (th.deco.kaomoji != null) text.kaomoji = th.deco.kaomoji;
  return {
    ...s,
    text,
    colors: { ...s.colors, mainText: th.mainColor, topText: th.topColor, bottomText: th.botColor, ...th.decoColors },
    grads: {
      ...s.grads,
      mainText: th.mainGrad
        ? { on: true, c1: th.mainGrad.c1, c2: th.mainGrad.c2, rainbow: th.mainGrad.rainbow }
        : { ...s.grads.mainText, on: false, rainbow: false },
    },
    noColor: { ...s.noColor, mainText: false, topText: false, bottomText: false, ...th.noColor },
    fonts: { ...s.fonts, topText: 'normal' as const, mainText: 'normal' as const, bottomText: 'normal' as const, ...th.fonts },
    // A category may set its own sizes (Little Notes runs its big word at 44).
    sizes: { ...createDefaultState().sizes, ...th.sizes },
    lineOrder: th.lineOrder ? [...th.lineOrder] : s.lineOrder,
    // Ranges belong to the words they were drawn on, and a card brings its own.
    ranges: {},
  };
}
