export const it = (l: string, main: string, top: string, bottom: string, theme?: Partial<TplTheme>): TplItem =>
  (theme ? { l, main, top, bottom, theme } : { l, main, top, bottom });
export const th = (mainColor: string, topColor: string, botColor: string, deco: TplDeco, mainGrad: TplTheme['mainGrad'] = null): TplTheme => ({ mainColor, topColor, botColor, mainGrad, deco });
export const deco = (dekoTop: string, dekoBottom: string, kaomoji: string): TplDeco => ({ dekoTop, dekoBottom, kaomoji });
